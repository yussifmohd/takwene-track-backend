# shellcheck shell=bash
# Launch template and Auto Scaling group: ASG_DESIRED instances (at least two) of INSTANCE_TYPE on the
# latest Amazon Linux 2023, spread over the public subnets and registered in both target groups.
#   - IMDSv2 only, encrypted gp3 root volume, no SSH key (Systems Manager instead);
#   - the user data installs Docker and the start script, then starts the current release if any;
#   - CPU target tracking scales between ASG_MIN and ASG_MAX.
# The group starts with EC2 health checks; deploy.sh switches it to load-balancer health checks after
# the first successful release (before that no instance can pass the load balancer's checks).
# Cost: the instances per hour, their volumes, and their public IPv4 addresses.

readonly AMI_PARAMETER="resolve:ssm:/aws/service/ami-amazon-linux-latest/al2023-ami-kernel-default-x86_64"

render_user_data() {
  cat <<EOF
#!/bin/bash
# Track Management ${ENVIRONMENT} instance bootstrap (generated by infra/aws/setup.sh).
set -euo pipefail
install -d -m 755 /etc/trackmgmt /opt/trackmgmt
cat >/etc/trackmgmt/app.conf <<'CONF'
AWS_REGION=${AWS_REGION}
ENVIRONMENT=${ENVIRONMENT}
NAME_PREFIX=${NAME_PREFIX}
SSM_PREFIX=${SSM_PREFIX}
REGISTRY=${REGISTRY}
LOG_GROUP=${LOG_GROUP}
VPC_CIDR=${VPC_CIDR}
ADMIN_EMAIL=${ADMIN_EMAIL}
DB_NAME=${DB_NAME}
DB_USERNAME=${DB_USERNAME}
DB_SSL_MODE=${DB_SSL_MODE}
CONF
chmod 644 /etc/trackmgmt/app.conf
cat >/opt/trackmgmt/run-app.sh <<'RUNAPP'
$(cat "$INFRA_DIR/instance/run-app.sh")
RUNAPP
chmod 755 /opt/trackmgmt/run-app.sh
$(cat "$INFRA_DIR/instance/bootstrap.sh")
EOF
}

step_compute() {
  local lt_name="${NAME_PREFIX}-lt" asg_name="${NAME_PREFIX}-asg" profile="${NAME_PREFIX}-ec2-profile"
  local vpc_id app_sg tg_api tg_web user_data data="$WORK_DIR/lt.json" description current_version
  local current_description version asg subnets lt_changed=false
  local -a public
  log "Instances (launch template + Auto Scaling group)"

  vpc_id="$(find_vpc_id)"
  [[ -n "$vpc_id" ]] || die "VPC not found; run the network step first."
  app_sg="$(find_sg_id "$vpc_id" "${NAME_PREFIX}-app")"
  [[ -n "$app_sg" ]] || die "Security group ${NAME_PREFIX}-app not found."
  tg_api="$(find_tg_arn "${NAME_PREFIX}-api")"
  tg_web="$(find_tg_arn "${NAME_PREFIX}-web")"
  [[ -n "$tg_api" && -n "$tg_web" ]] || die "Target groups not found; run the alb step first."
  subnets="$(subnet_ids "$vpc_id" public)"
  read -r -a public <<<"$subnets"

  user_data="$(render_user_data | base64 | tr -d '\n')"
  cat >"$data" <<EOF
{
  "ImageId": "$AMI_PARAMETER",
  "InstanceType": "$INSTANCE_TYPE",
  "IamInstanceProfile": {"Name": "$profile"},
  "SecurityGroupIds": ["$app_sg"],
  "MetadataOptions": {"HttpTokens": "required", "HttpPutResponseHopLimit": 1, "HttpEndpoint": "enabled"},
  "BlockDeviceMappings": [{"DeviceName": "/dev/xvda",
    "Ebs": {"VolumeSize": $EBS_VOLUME_GB, "VolumeType": "gp3", "Encrypted": true, "DeleteOnTermination": true}}],
  "TagSpecifications": [{"ResourceType": "volume", "Tags": $(tags_json "${NAME_PREFIX}-app")}],
  "UserData": "$user_data"
}
EOF
  # The version description carries a hash of the template, so a re-run only adds a version on change.
  description="config-sha256:$(sha256_of "$data")"

  current_version="$(aws_lookup 'NotFound' ec2 describe-launch-templates \
    --launch-template-names "$lt_name" --query 'LaunchTemplates[0].DefaultVersionNumber')"
  if [[ -z "$current_version" ]]; then
    awsr ec2 create-launch-template --launch-template-name "$lt_name" \
      --version-description "$description" --launch-template-data "$(file_arg "$data")" \
      --tag-specifications "$(tag_spec launch-template "$lt_name")" >/dev/null
    log "  created launch template $lt_name"
  else
    current_description="$(awst ec2 describe-launch-template-versions --launch-template-name "$lt_name" \
      --versions "$current_version" --query 'LaunchTemplateVersions[0].VersionDescription')"
    if [[ "$current_description" == "$description" ]]; then
      log "  exists  launch template $lt_name (version $current_version, unchanged)"
    else
      version="$(awst ec2 create-launch-template-version --launch-template-name "$lt_name" \
        --version-description "$description" --launch-template-data "$(file_arg "$data")" \
        --query LaunchTemplateVersion.VersionNumber)"
      awsr ec2 modify-launch-template --launch-template-name "$lt_name" --default-version "$version" >/dev/null
      lt_changed=true
      log "  updated launch template $lt_name to version $version"
    fi
  fi

  asg="$(find_asg_name)"
  if [[ -z "$asg" ]]; then
    awsr autoscaling create-auto-scaling-group --auto-scaling-group-name "$asg_name" \
      --launch-template "LaunchTemplateName=$lt_name,Version=\$Default" \
      --min-size "$ASG_MIN" --max-size "$ASG_MAX" --desired-capacity "$ASG_DESIRED" \
      --vpc-zone-identifier "$(IFS=,; echo "${public[*]}")" \
      --target-group-arns "$tg_api" "$tg_web" \
      --health-check-type EC2 --health-check-grace-period 300 \
      --tags "ResourceId=$asg_name,ResourceType=auto-scaling-group,Key=Name,Value=${NAME_PREFIX}-app,PropagateAtLaunch=true" \
             "ResourceId=$asg_name,ResourceType=auto-scaling-group,Key=Project,Value=$PROJECT_TAG,PropagateAtLaunch=true" \
             "ResourceId=$asg_name,ResourceType=auto-scaling-group,Key=Environment,Value=$ENVIRONMENT,PropagateAtLaunch=true"
    log "  created Auto Scaling group $asg_name ($ASG_DESIRED x $INSTANCE_TYPE)"
  else
    awsr autoscaling update-auto-scaling-group --auto-scaling-group-name "$asg_name" \
      --launch-template "LaunchTemplateName=$lt_name,Version=\$Default" \
      --min-size "$ASG_MIN" --max-size "$ASG_MAX"
    log "  exists  Auto Scaling group $asg_name (min $ASG_MIN, max $ASG_MAX)"
    if [[ "$lt_changed" == true ]]; then
      warn "Running instances still use the old launch template. Replace them with:"
      warn "  ./deploy.sh --env $ENVIRONMENT --refresh-instances"
    fi
  fi

  if (( ASG_MAX > ASG_MIN )); then
    awsr autoscaling put-scaling-policy --auto-scaling-group-name "$asg_name" \
      --policy-name "${NAME_PREFIX}-cpu-target" --policy-type TargetTrackingScaling \
      --target-tracking-configuration \
      "{\"PredefinedMetricSpecification\":{\"PredefinedMetricType\":\"ASGAverageCPUUtilization\"},\"TargetValue\":$SCALE_CPU_TARGET}" \
      >/dev/null
    log "  scaling policy: average CPU $SCALE_CPU_TARGET% (between $ASG_MIN and $ASG_MAX instances)"
  fi
}
